"""Updates the texts of the language folders (languages/<id>/port.txt) from the sources.

See docs/TRANSLATING.md.

The texts are the English ones the game hands to tr(): the tr("...") calls of
the game's sources (not the level editor's), the controller's actions and
buttons (src/core/pad_config.hpp) and the item names (src/core/dtable.cpp).

- languages/en/port.txt is written from them: every text, translated by
  itself. It is the reference a new language starts from.
- Every other languages/<id>/port.txt is rewritten in the same order: its leading
  comments, "@name" and translations are kept, the new texts are added with an
  empty translation, and the texts the game no longer uses are kept at the end
  in comments.

Usage: python scripts/update_languages.py [--check]
--check writes nothing: it exits with 1 when a file would change, or when
languages/fr/port.txt (the French executable's texts, which the French data needs)
misses a translation. It is a ctest.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
languages = root / 'languages'

LIT = r'"(?:[^"\\]|\\.)*"'
LITS = rf'{LIT}(?:\s*{LIT})*'
TR1 = re.compile(rf'\btr\(\s*({LITS})\s*\)', re.S)
TR2 = re.compile(rf'\btr\(\s*{LITS}\s*,', re.S)

EN_HEADER = '''\
# English texts of the port: the reference for the other languages.
#
# Generated by scripts/update_languages.py from the sources: do not edit (an
# English text is changed in the code). To translate the port, copy this file
# to languages/<language>/port.txt and follow docs/TRANSLATING.md.
#
# Each line: an English text, "=", its translation. "\\n" is a line break.
'''

NOTES = {
    'src/engine/ui/computer_gump.hpp': 'computer terminals',
    'src/engine/ui/enhancements_screen.cpp': 'enhancements window',
    'src/engine/ui/gamepad_screen.cpp': 'controller screen',
    'src/engine/ui/load_screen.cpp': 'load and save screen',
    'src/engine/ui/options_screen.cpp': 'options screen',
    'src/engine/ui/status_bar.cpp': 'status bar',
    'src/engine/ui/weasel_gump.cpp': "Weasel's shop, No Remorse only",
    'src/engine/world/pickup_list.cpp': 'items picked up',
    'src/engine/world/player_commands.cpp': 'messages',
    'src/game/game.cpp': 'main menu and saves',
}


def c_string(text):
    """The bytes of adjacent C string literals, as code page 850 text."""
    out = b''
    for part in re.findall(LIT, text):
        body, i = part[1:-1], 0
        while i < len(body):
            if body[i] != '\\':
                out += body[i].encode('ascii')
                i += 1
            elif body[i + 1] == 'x':
                digits = re.match(r'[0-9a-fA-F]{1,2}', body[i + 2:]).group(0)
                out += bytes([int(digits, 16)])
                i += 2 + len(digits)
            else:
                out += {'n': b'\n', 't': b'\t', '"': b'"', "'": b"'", '\\': b'\\'}[body[i + 1]]
                i += 2
    return out.decode('cp850')


def string_array(source, name):
    match = re.search(rf'\b{name}\s*=\s*\{{\{{?(.*?)\}}\}}?;', source, re.S)
    if not match:
        sys.exit(f'{name} not found')
    return match.group(1)


def sections():
    """[(title, [english...])], in the order of the files."""
    found = []
    errors = []
    for path in sorted(root.glob('src/**/*.[ch]pp')):
        rel = path.relative_to(root).as_posix()
        if rel.startswith('src/editor/') or rel == 'src/core/language.hpp':
            continue
        source = path.read_text(encoding='utf-8')
        for m in TR2.finditer(source):
            errors.append(f'{rel}:{source.count(chr(10), 0, m.start()) + 1}: tr() with two texts outside the editor')
        texts = [c_string(m.group(1)) for m in TR1.finditer(source)]
        if texts:
            found.append((f'{NOTES[rel]} ({rel})' if rel in NOTES else rel, texts))
    if errors:
        sys.exit('\n'.join(errors))

    pad = (root / 'src/core/pad_config.hpp').read_text(encoding='utf-8')
    actions = [c_string(m) for m in re.findall(rf'\{{\s*({LIT})\s*,', string_array(pad, 'kPadActions'))]
    # The button names A, LB... are not translated.
    buttons = [c_string(m) for m in re.findall(LIT, string_array(pad, 'kPadButtonLabels')) if len(c_string(m)) > 2]
    found.append(('controller actions and buttons (src/core/pad_config.hpp)', actions + buttons))

    dtable = (root / 'src/core/dtable.cpp').read_text(encoding='utf-8')
    for title, tables in (('item names, No Regret', ('kRegretItemNames', 'kRegretAmmoNames', 'kRegretFamily12Names')),
                          ('item names, No Remorse', ('kItemNames', 'kAmmoNames', 'kFamily12Names'))):
        # The No Remorse port has no No Regret tables.
        if not re.search(rf'\b{tables[0]}\s*=', dtable):
            continue
        texts = [c_string(m) for table in tables for m in re.findall(LIT, string_array(dtable, table))]
        found.append((f'{title} (src/core/dtable.cpp)', texts))

    # Once each, in the first place it is used; "INVALID" (no item) is not
    # translated.
    seen = set()
    out = []
    for title, texts in found:
        keep = []
        for text in texts:
            if text in seen or text == 'INVALID':
                continue
            seen.add(text)
            keep.append(text)
        if keep:
            out.append((title, keep))
    return out


def escape(text):
    return text.replace('\\', '\\\\').replace('\n', '\\n')


def unescape(text):
    return re.sub(r'\\([n\\])', lambda m: '\n' if m.group(1) == 'n' else '\\', text)


def parse(text):
    """(leading comment lines, name, {english: translation}), as the game reads it."""
    header, name, texts = [], '', {}
    in_header = True
    for line in text.lstrip('﻿').splitlines():
        stripped = line.strip()
        if in_header and (stripped.startswith('#') or not stripped):
            header.append(line.rstrip())
            continue
        in_header = False
        if not stripped or stripped.startswith('#') or '=' not in stripped:
            continue
        key, value = (unescape(part.strip()) for part in stripped.split('=', 1))
        if key == '@name':
            name = value
        elif key:
            texts[key] = value
    while header and not header[-1]:
        header.pop()
    return header, name, texts


def write(header, name, texts, found, keep_unused):
    out = '\n'.join(header) + '\n\n' if header else ''
    out += f'@name = {name}\n'
    used = set()
    for title, keys in found:
        out += f'\n# --- {title}\n'
        for key in keys:
            used.add(key)
            value = texts.get(key, '')
            out += f'{escape(key)} = {escape(value)}'.rstrip() + '\n'
    unused = [k for k in texts if k not in used and texts[k]] if keep_unused else []
    if unused:
        out += '\n# --- no longer used by the game\n'
        out += ''.join(f'# {escape(k)} = {escape(texts[k])}\n' for k in unused)
    return out


def main():
    check = '--check' in sys.argv[1:]
    found = sections()
    keys = [k for _, ks in found for k in ks]
    english = languages / 'en' / 'port.txt'
    wanted = {english: write(EN_HEADER.rstrip('\n').split('\n'), 'ENGLISH', {k: k for k in keys}, found, False)}
    for path in sorted(languages.glob('*/port.txt')):
        if path == english:
            continue
        header, name, texts = parse(path.read_text(encoding='utf-8'))
        if header == EN_HEADER.rstrip('\n').split('\n'):  # a copy of en.txt
            header = ['# Texts of the port in another language: see docs/TRANSLATING.md.']
        wanted[path] = write(header, name, texts, found, True)
    failed = False
    for path, text in wanted.items():
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current != text:
            if check:
                print(f'{path.relative_to(root)} is out of date: run python scripts/update_languages.py')
                failed = True
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8', newline='\n')
                print(f'updated {path.relative_to(root)}')
    french = languages / 'fr' / 'port.txt'
    if french.exists():
        missing = [k for k in keys if not parse(french.read_text(encoding='utf-8'))[2].get(k)]
        for k in missing:
            print(f'languages/fr/port.txt: no translation of "{escape(k)}"')
        failed = failed or bool(missing)
    return 1 if failed and check else 0


if __name__ == '__main__':
    sys.exit(main())
