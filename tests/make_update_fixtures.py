import io, sys, zipfile, tarfile, gzip, hashlib, zlib

def exe(tag):
    s = tag + "\n"
    for i in range(120):
        s += "line %d of the new executable\n" % (i * i)
    return s.encode()

FILES = [  # (path, content, mode, method)
    ("pkg/README.md", b"readme 2\n", 0o644, "deflate"),
    ("pkg/languages/fr/port.txt", ("NEW = NOUVEAU\n" * 40).encode(), 0o644, "deflate"),
    ("pkg/data/PUT_GAME_DATA_HERE.txt", b"put the data here\n", 0o644, "store"),
    ("pkg/ceiling_lights/map001.json", b'{"lamps": []}\n', 0o644, "store"),
    ("pkg/crusader-no-remorse.exe", exe("NEWEXE"), 0o755, "deflate"),
    ("pkg/crusader-no-remorse-editor.exe", exe("NEWEDITOR"), 0o755, "deflate"),
]

def make_zip(files, dirs=True):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        if dirs:
            zi = zipfile.ZipInfo("pkg/", date_time=(2026, 11, 25, 12, 0, 0))
            zi.external_attr = (0o40755 << 16) | 0x10
            z.writestr(zi, b"")
        for path, content, mode, method in files:
            zi = zipfile.ZipInfo(path, date_time=(2026, 11, 25, 12, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED if method == "deflate" else zipfile.ZIP_STORED
            zi.external_attr = (mode | 0o100000) << 16
            zi.create_system = 3
            z.writestr(zi, content)
    return buf.getvalue()

def make_targz(files):
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as t:
        d = tarfile.TarInfo("pkg"); d.type = tarfile.DIRTYPE; d.mode = 0o755; d.mtime = 1795629600
        t.addfile(d)
        for path, content, mode, method in files:
            ti = tarfile.TarInfo(path); ti.size = len(content); ti.mode = mode; ti.mtime = 1795629600
            t.addfile(ti, io.BytesIO(content))
        # a long path, with a prefix
        long_path = "pkg/languages/" + "d" * 90 + "/" + "f" * 40 + ".txt"
        ti = tarfile.TarInfo(long_path); ti.size = 3; ti.mode = 0o644; ti.mtime = 1795629600
        t.addfile(ti, io.BytesIO(b"abc"))
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", mtime=0, filename="pkg.tar") as g:
        g.write(raw.getvalue())
    return out.getvalue()

def array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    return "inline const std::uint8_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))

zip_bytes = make_zip(FILES)
evil = make_zip([("pkg/../evil.txt", b"x", 0o644, "store")], dirs=False)
targz = make_targz(FILES)
# a raw deflate stream: zlib minus its 2 byte header and 4 byte trailer, over a text with all block kinds
text = "".join("%d:%s\n" % (i, "abc" * (i % 7)) for i in range(400)).encode()
comp = zlib.compressobj(9, zlib.DEFLATED, -15)
deflated = comp.compress(text) + comp.flush()
# a fixed-Huffman stream (short input) and a stored block
fixed = zlib.compressobj(9, zlib.DEFLATED, -15, 9, zlib.Z_FIXED); fixed_bytes = fixed.compress(b"hello hello hello hello") + fixed.flush()
stored = zlib.compressobj(0, zlib.DEFLATED, -15); stored_bytes = stored.compress(b"stored block") + stored.flush()

out = ["#pragma once", "// Generated by tests/make_update_fixtures.py (python make_update_fixtures.py > update_fixtures.hpp):",
       "// the archives of the self-update's tests (update_tests.cpp).",
       "#include <cstdint>", ""]
out.append("// zip, deflate and stored entries, in this order: " + ", ".join(f[0] for f in FILES))
out.append(array("kZip", zip_bytes))
out.append("// a zip with the path pkg/../evil.txt")
out.append(array("kEvilZip", evil))
out.append("// the same files as a tar.gz (ustar), and a file with a long path (prefix)")
out.append(array("kTarGz", targz))
out.append("// raw deflate (dynamic Huffman) of text(); the digest of the text: " + hashlib.sha256(text).hexdigest())
out.append(array("kDeflated", deflated))
out.append("inline const std::uint8_t kDeflatedFixed[] = {" + ", ".join("0x%02x" % b for b in fixed_bytes) + "};  // \"hello hello hello hello\"")
out.append("inline const std::uint8_t kDeflatedStored[] = {" + ", ".join("0x%02x" % b for b in stored_bytes) + "};  // \"stored block\"")
sys.stdout.write("\n".join(out) + "\n")
print("zip", len(zip_bytes), "targz", len(targz), "deflated", len(deflated), file=sys.stderr)
